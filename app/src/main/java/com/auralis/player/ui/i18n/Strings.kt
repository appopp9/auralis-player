val LocalStrings = compositionLocalOf { EnglishStrings }

/** Applies the selected language + matching layout direction to a subtree. */
@Composable
fun AuralisLocalization(language: AppLanguage, content: @Composable () -> Unit) {
    val strings = when (language) {
        AppLanguage.PERSIAN -> PersianStrings
        AppLanguage.ENGLISH -> EnglishStrings
        AppLanguage.SYSTEM -> if (isSystemPersian()) PersianStrings else EnglishStrings
    }
    CompositionLocalProvider(
        LocalStrings provides strings,
        LocalLayoutDirection provides if (strings.rtl) LayoutDirection.Rtl else LayoutDirection.Ltr,
        content = content
    )
}

private fun isSystemPersian(): Boolean =
    java.util.Locale.getDefault().language.let { it == "fa" || it == "per" }
